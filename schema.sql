-- 1.CATEGORY TABLE
create table public.category (
  category_id bigint generated by default as identity not null,
  category_name character varying(255) not null,
  transaction_type character varying(50) null,
  constraint category_pkey primary key (category_id)
) TABLESPACE pg_default;
-- 2.FINANCIAL_TRANSACTION TABLE
create table public.financial_transaction (
  transaction_id bigint generated by default as identity not null,
  category_id bigint null,
  purchase_id bigint null,
  sale_id bigint null,
  transaction_date timestamp with time zone null default timezone ('utc'::text, now()),
  amount numeric(12, 2) not null,
  description text null,
  purchase_order_id bigint null,
  sale_order_id bigint null,
  constraint financial_transaction_pkey primary key (transaction_id),
  constraint financial_transaction_category_id_fkey foreign KEY (category_id) references category (category_id) on delete RESTRICT,
  constraint financial_transaction_purchase_id_fkey foreign KEY (purchase_id) references purchase_order (purchase_id) on delete CASCADE,
  constraint financial_transaction_sale_id_fkey foreign KEY (sale_id) references sale_order (sale_id) on delete CASCADE,
  constraint fk_financial_purchase foreign KEY (purchase_order_id) references purchase_order (purchase_id) on delete set null,
  constraint fk_financial_sale foreign KEY (sale_order_id) references sale_order (sale_id) on delete set null
) TABLESPACE pg_default;

-- 3.PRODUCT_INVENTORY TABLE
create table public.product_inventory (
  product_id bigint generated by default as identity not null,
  product_name character varying(255) not null,
  quantity_in_stock integer null default 0,
  unit_id bigint null,
  constraint product_inventory_pkey primary key (product_id),
  constraint product_inventory_unit_id_fkey foreign KEY (unit_id) references unit (unit_id) on delete RESTRICT
) TABLESPACE pg_default;

--4.PURCHASE_DETAIL TABLE
create table public.purchase_detail (
  purchase_detail_id bigint generated by default as identity not null,
  purchase_id bigint null,
  product_id bigint null,
  quantity integer not null,
  unit_price numeric(12, 2) not null,
  constraint purchase_detail_pkey primary key (purchase_detail_id),
  constraint purchase_detail_product_id_fkey foreign KEY (product_id) references product_inventory (product_id) on delete RESTRICT,
  constraint purchase_detail_purchase_id_fkey foreign KEY (purchase_id) references purchase_order (purchase_id) on delete CASCADE
) TABLESPACE pg_default;

--5.PURCHASE_ORDER TABLE
create table public.purchase_order (
  purchase_id bigint generated by default as identity not null,
  supplier_id bigint null,
  purchase_date timestamp with time zone null default timezone ('utc'::text, now()),
  total_amount numeric(12, 2) null default 0,
  constraint purchase_order_pkey primary key (purchase_id),
  constraint purchase_order_supplier_id_fkey foreign KEY (supplier_id) references supplier (supplier_id) on delete set null
) TABLESPACE pg_default;
--6.SALE_DETAIL TABLE
create table public.sale_detail (
  sale_detail_id bigint generated by default as identity not null,
  sale_id bigint null,
  product_id bigint null,
  quantity integer not null,
  unit_price numeric(12, 2) not null,
  constraint sale_detail_pkey primary key (sale_detail_id),
  constraint sale_detail_product_id_fkey foreign KEY (product_id) references product_inventory (product_id) on delete RESTRICT,
  constraint sale_detail_sale_id_fkey foreign KEY (sale_id) references sale_order (sale_id) on delete CASCADE
) TABLESPACE pg_default;
--7.SALE_ORDER TABLE
create table public.sale_order (
  sale_id bigint generated by default as identity not null,
  customer_name character varying(255) null,
  sale_date timestamp with time zone null default timezone ('utc'::text, now()),
  total_amount numeric(12, 2) null default 0,
  constraint sale_order_pkey primary key (sale_id)
) TABLESPACE pg_default;
--8.SUPPLIER TABLE
create table public.supplier (
  supplier_id bigint generated by default as identity not null,
  supplier_name character varying(255) not null,
  phone_number character varying(50) null,
  address text null,
  constraint supplier_pkey primary key (supplier_id)
) TABLESPACE pg_default;
--9.UNIT TABLE
create table public.unit (
  unit_id bigint generated by default as identity not null,
  unit_name character varying(50) not null,
  constraint unit_pkey primary key (unit_id)
) TABLESPACE pg_default;